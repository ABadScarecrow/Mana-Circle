import {test} from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import {openDatabase} from '../src/server/db';
import {createApp} from '../src/server/app';
test('auth, privacy, partial imports and idempotent missing-card additions',async()=>{
 const db=openDatabase(':memory:');
 const resolve=async(name:string)=>{if(name==='Unknown' || name==='bad line')throw Error('Carte inconnue');const card={oracle_id:'oracle-bolt',name:'Lightning Bolt',image:null,type_line:'Instant'};db.prepare('INSERT OR IGNORE INTO cards VALUES (?,?,?,?)').run(card.oracle_id,card.name,null,card.type_line);return card;};
 const app=createApp(db,resolve);const alice=request.agent(app),bob=request.agent(app);
 const send=(agent:typeof alice,path:string,body:object)=>agent.post(path).set('X-Mana-Request','1').send(body);
 await request(app).get('/api/matches').expect(401);
 await send(alice,'/api/auth/register',{username:'alice',password:'correct horse battery'}).expect(200);
 await send(bob,'/api/auth/register',{username:'bobby',password:'correct horse battery'}).expect(200);
 await alice.put('/api/wishlist').set('X-Mana-Request','1').send({name:'Lightning Bolt',quantity:4}).expect(200);
 await bob.put('/api/collection').set('X-Mana-Request','1').send({name:'Lightning Bolt',quantity:3}).expect(200);
 assert.equal((await alice.get('/api/matches')).body.receive.length,0);
 await send(alice,'/api/friends',{username:'bobby'}).expect(201);
 const relation=(await bob.get('/api/friends')).body[0];
 await alice.patch('/api/friends/'+relation.id).set('X-Mana-Request','1').send({action:'accept'}).expect(404);
 assert.equal((await alice.get('/api/matches')).body.receive.length,0);
 await bob.patch('/api/friends/'+relation.id).set('X-Mana-Request','1').send({action:'accept'}).expect(200);
 assert.equal((await alice.get('/api/matches')).body.receive[0].available,3);
 const partial=await send(alice,'/api/decks/import',{name:'Partial',text:'4 Lightning Bolt\nbad line\n1 Unknown'}).expect(201);
 assert.equal(partial.body.imported,1);assert.equal(partial.body.errors.length,2);
 assert.equal(partial.body.retryText,'mainboard\nbad line\n1 Unknown');
 assert.equal((await alice.get('/api/decks')).body.length,1);
 const retry=await send(alice,'/api/decks/import',{deckId:partial.body.id,text:'Lightning Bolt'}).expect(201);
 assert.equal(retry.body.id,partial.body.id);
 const partialDeck=(await alice.get('/api/decks')).body.find((d:any)=>d.id===partial.body.id);assert.equal(partialDeck.cards.reduce((n:number,c:any)=>n+c.quantity,0),5);
 await send(bob,'/api/decks/import',{deckId:partial.body.id,text:'Lightning Bolt'}).expect(404);
 const collectionImport=await send(alice,'/api/collection/import',{text:'Lightning Bolt\n3 Lightning Bolt\nUnknown\n0 Island'}).expect(201);
 assert.equal(collectionImport.body.imported,2);assert.equal(collectionImport.body.errors.length,2);
 assert.equal((await alice.get('/api/collection')).body[0].quantity,4);
 await alice.delete('/api/collection/oracle-bolt').set('X-Mana-Request','1').expect(200);
 await send(alice,'/api/collection/import',{text:'Unknown'}).expect(422);
 const overflow=await send(alice,'/api/collection/import',{text:'9999 Lightning Bolt\nLightning Bolt'}).expect(201);
 assert.equal(overflow.body.imported,1);assert.equal(overflow.body.errors.length,1);
 await alice.delete('/api/collection/oracle-bolt').set('X-Mana-Request','1').expect(200);
 const sectionError=await send(alice,'/api/decks/import',{deckId:partial.body.id,text:'Sideboard\n0 Negate'}).expect(422);
 assert.equal(sectionError.body.errors[0].section,'sideboard');
 assert.equal(sectionError.body.errors[0].retryText,'sideboard\n0 Negate');
 const deck=await send(alice,'/api/decks/import',{name:'Burn',text:'4 Lightning Bolt\nSideboard\n2 Lightning Bolt'}).expect(201);
 await send(bob,'/api/decks/'+deck.body.id+'/missing',{}).expect(404);
 await send(alice,'/api/decks/'+deck.body.id+'/missing',{}).expect(200);
 await send(alice,'/api/decks/'+deck.body.id+'/missing',{}).expect(200);
 assert.equal((await alice.get('/api/wishlist')).body[0].quantity,6);
 await alice.delete('/api/friends/'+relation.id).set('X-Mana-Request','1').expect(200);
 assert.equal((await alice.get('/api/matches')).body.receive.length,0);
 await alice.put('/api/collection').send({name:'Lightning Bolt',quantity:1}).expect(403);
 await send(alice,'/api/auth/logout',{}).expect(200);await alice.get('/api/me').expect(401);db.close();
});
